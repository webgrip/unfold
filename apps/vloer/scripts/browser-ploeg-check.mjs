import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { application } from '../test/api-support.ts';

const app = await application();
const screenshots = process.env.VLOER_SCREENSHOTS ? resolve(process.env.VLOER_SCREENSHOTS) : undefined;
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.VLOER_CHROMIUM_BIN ? { executablePath: process.env.VLOER_CHROMIUM_BIN } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1040 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const screenshot = async name => { if (screenshots) { await mkdir(screenshots, { recursive: true }); await page.screenshot({ path: join(screenshots, `${name}.png`), fullPage: true }); } };
  await page.goto(`${app.url}/#ploeg`);
  await page.getByRole('heading', { name: 'Follow the work.', exact: true }).waitFor();
  await page.getByText('Illustrative Ploeg records. These runs were not executed; no model calls or charges.', { exact: true }).waitFor();
  await page.getByText('Pause state not reported', { exact: true }).waitFor();
  await screenshot('ploeg-overview');
  await page.locator('[data-action="ploeg-item"][data-id="101"]').click();
  await page.getByRole('heading', { name: 'Review the rounding acceptance criteria', exact: true }).waitFor();
  await page.getByText('The acceptance criteria need a human decision.', { exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Shifts & spending', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Checkpoints', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Audit snapshot', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'ploeg-item-title');
  await screenshot('ploeg-review');
  await page.reload();
  await page.getByRole('heading', { name: 'Review the rounding acceptance criteria', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Ploeg details overflow mobile');
  assert.equal(await page.locator('.ploeg-list-panel').isVisible(), false);
  await screenshot('ploeg-review-mobile');
  await page.getByRole('button', { name: 'Close work item details', exact: true }).click();
  await page.locator('[data-action="ploeg-item"][data-id="101"]').waitFor();
  await page.locator('.ploeg-metric[data-id="leased"]').click();
  await page.locator('[data-action="ploeg-item"][data-id="102"]').click();
  await page.getByRole('heading', { name: 'Prepare a regression investigation', exact: true }).waitFor();
  await page.getByText('Illustration · no model calls', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'Ploeg team', exact: true }).selectOption('research');
  await page.getByText('No work in this view', { exact: true }).waitFor();
  await page.locator('.ploeg-metric[data-id="queued"]').click();
  await page.locator('[data-action="ploeg-item"][data-id="104"]').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Ploeg overview overflows mobile');
  await screenshot('ploeg-queue-mobile');
  await page.getByRole('combobox', { name: 'Ploeg team', exact: true }).selectOption('delivery');
  await page.locator('[data-action="ploeg-item"][data-id="103"]').waitFor();
  await page.setViewportSize({ width: 1440, height: 1040 });
  const detailUrl = `${app.url}/api/ploeg/work-items/101`;
  const original = await (await page.request.get(detailUrl)).json();
  const hostile = structuredClone(original);
  hostile.demo = false;
  hostile.runs[0].findings = '<img id="hostile-ploeg" src="/untrusted" onerror="alert(1)">\nTreat this as review text.';
  hostile.item.url = 'javascript:alert(1)';
  hostile.runs[0].links = ['javascript:alert(1)'];
  hostile.truncated.runs = true;
  await page.route(detailUrl, route => route.fulfill({ json: hostile }));
  await page.goto(`${app.url}/#ploeg/101`);
  await page.getByText(hostile.runs[0].findings, { exact: true }).waitFor();
  await page.getByText('Unknown · not reported', { exact: true }).waitFor();
  await page.getByText('Ploeg capped this history. Earlier records may be omitted.', { exact: true }).waitFor();
  assert.equal(await page.locator('#hostile-ploeg, a[href^="javascript:"]').count(), 0, 'Untrusted execution evidence became active content');
  await page.unroute(detailUrl);
  const pageFixture = await (await page.request.get(`${app.url}/api/ploeg?team=delivery`)).json();
  pageFixture.lanes.queued.nextCursor = '9007199254740993';
  await page.route('**/api/ploeg?*', route => route.fulfill({ json: pageFixture }));
  await page.route('**/api/ploeg/work-items?*', route => {
    assert.equal(new URL(route.request().url()).searchParams.get('after'), '9007199254740993');
    const item = { ...pageFixture.lanes.queued.items[0], id: '9007199254740994', title: 'Loaded from a second snapshot page' };
    return route.fulfill({ json: { items: [item], nextCursor: null } });
  });
  await page.goto(`${app.url}/#ploeg`);
  await page.getByRole('button', { name: 'Load more', exact: false }).click();
  await page.getByText('Loaded from a second snapshot page', { exact: true }).waitFor();
  assert.equal(await page.locator('[data-action="ploeg-more"]').count(), 0);
  await page.unroute('**/api/ploeg?*');
  await page.unroute('**/api/ploeg/work-items?*');
  await page.route('**/api/ploeg?*', route => route.fulfill({ json: { configured: true, available: false, demo: false, teams: [], message: 'Ploeg operator connection is unavailable.' } }));
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByRole('heading', { name: 'Ploeg needs attention', exact: true }).waitFor();
  assert.equal(await page.locator('[data-action="ploeg-item"]').count(), 0, 'Unavailable connection retained stale actionable items');
  await screenshot('ploeg-unavailable');
  await page.getByRole('link', { name: 'Sessions', exact: true }).click();
  await page.getByRole('heading', { name: 'Sessions', exact: true }).first().waitFor();
  assert.equal(app.app.store.listSessions().length, 0, 'Operator browsing created paid execution');
  assert.deepEqual(errors, []);
  process.stdout.write(`PASS: Chromium ${browser.version()}; Ploeg overview, evidence, deep links, team filters, mobile layouts, opaque pagination, inert untrusted content, unknown costs, truncation and outage recovery. No inference or dispatch requests.\n`);
} finally { await browser?.close(); await app.close(); }
