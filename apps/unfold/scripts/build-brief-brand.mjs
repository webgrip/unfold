import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repository = new URL('../../../', import.meta.url);
const target = fileURLToPath(new URL('../extensions/claude-code/brief/brand.mjs', import.meta.url));
const sources = {
  tokensCss: 'docs/brand/tokens.css',
  markSvg: 'docs/brand/mark.svg',
  wordmarkSvg: 'docs/brand/wordmark.svg',
};

export function briefBrandModule() {
  const exports = Object.entries(sources).map(([name, path]) => {
    const text = readFileSync(new URL(path, repository), 'utf8');
    return `/** Generated by apps/unfold/scripts/build-brief-brand.mjs from ${path}; run it after the brand changes. */\nexport const ${name} = ${JSON.stringify(text)};\n`;
  });
  return exports.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = briefBrandModule();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch {}
    if (current !== expected) {
      console.error(`${target} differs from docs/brand; run node apps/unfold/scripts/build-brief-brand.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(target, expected);
  }
}
