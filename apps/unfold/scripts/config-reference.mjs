import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const schemaPath = `${root}docs/contracts/config.v1.schema.json`;
const environmentPath = `${root}docs/contracts/config.v1.environment.json`;
const referencePath = `${root}docs/operations/configuration.md`;
const chartSchemaPath = `${root}ops/helm/unfold/values.schema.json`;
const check = process.argv.includes('--check');

/** Keys of the configuration file the Helm chart writes itself, and the chart value that sets each. */
export const chartOwned = {
  mode: 'the chart value mode',
  dataDir: 'the chart, as /data/workbench',
  publicDir: 'the chart, as /app/public',
  runtime: 'the chart, as the kubernetes backend',
  kubernetes: 'the chart\'s workspace* values',
};
/** Keys inside a configuration block the chart sets from its own values. */
export const chartOwnedNested = { auth: { localLogin: 'the chart value auth.localLogin' } };

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
const environment = JSON.parse(readFileSync(environmentPath, 'utf8'));

const plain = value => Boolean(value) && typeof value === 'object' && !Array.isArray(value);

function resolved(node) {
  if (!plain(node) || node.$ref === undefined) return node;
  const name = /^#\/\$defs\/(.+)$/.exec(node.$ref)?.[1];
  const target = name && schema.$defs?.[name];
  if (!target) throw new Error(`Unknown $ref ${node.$ref}`);
  const { $ref, ...rest } = node;
  return { ...resolved(target), ...rest };
}

function inline(node) {
  if (Array.isArray(node)) return node.map(inline);
  if (!plain(node)) return node;
  const flat = resolved(node);
  return Object.fromEntries(Object.entries(flat).map(([key, value]) => {
    if (key === 'properties' || key === '$defs') return [key, Object.fromEntries(Object.entries(value).map(([name, child]) => [name, inline(child)]))];
    if (['items', 'additionalProperties', 'propertyNames', 'not'].includes(key) && plain(value)) return [key, inline(value)];
    if (key === 'anyOf') return [key, value.map(inline)];
    return [key, value];
  }));
}

/** The chart's `config` subtree: the configuration schema inlined for draft-07, with the keys the chart writes refused. */
export function chartConfigSchema() {
  const config = inline(schema);
  const { $schema, $id, title, $defs, ...rest } = config;
  const { $schema: editorSchema, ...properties } = rest.properties;
  for (const [key, setBy] of Object.entries(chartOwned)) properties[key] = { not: {}, description: `Set by ${setBy}; leave it out of config.` };
  for (const [block, keys] of Object.entries(chartOwnedNested)) for (const [key, setBy] of Object.entries(keys)) properties[block].properties[key] = { not: {}, description: `Set by ${setBy}; leave it out of config.` };
  return { ...rest, description: 'The Unfold configuration file the chart renders, apart from the keys it writes itself (docs/contracts/config.v1.schema.json, generated by scripts/config-reference.mjs).', properties };
}

function compact(value) {
  if (Array.isArray(value)) return value.length ? `[${value.map(compact).join(', ')}]` : '[]';
  if (plain(value)) { const entries = Object.entries(value); return entries.length ? `{ ${entries.map(([key, item]) => `${JSON.stringify(key)}: ${compact(item)}`).join(', ')} }` : '{}'; }
  return JSON.stringify(value);
}

function pretty(value, indent) {
  const line = compact(value);
  if ((!Array.isArray(value) && !plain(value)) || indent.length + line.length <= 150) return line;
  const inner = `${indent}  `;
  if (Array.isArray(value)) return `[\n${value.map(item => `${inner}${pretty(item, inner)}`).join(',\n')}\n${indent}]`;
  return `{\n${Object.entries(value).map(([key, item]) => `${inner}${JSON.stringify(key)}: ${pretty(item, inner)}`).join(',\n')}\n${indent}}`;
}

function objectEnd(text, start) {
  let depth = 0;
  let inString = false;
  for (let index = start; index < text.length; index++) {
    const character = text[index];
    if (inString) { if (character === '\\') index++; else if (character === '"') inString = false; continue; }
    if (character === '"') inString = true;
    else if (character === '{') depth++;
    else if (character === '}' && --depth === 0) return index + 1;
  }
  throw new Error('values.schema.json: the config object never closes');
}

function chartSchemaText() {
  const text = readFileSync(chartSchemaPath, 'utf8');
  const marker = /^ {4}"config": \{/m.exec(text);
  if (!marker) throw new Error('values.schema.json has no top-level config property');
  const start = marker.index + marker[0].length - 1;
  const updated = `${text.slice(0, start)}${pretty(chartConfigSchema(), '    ')}${text.slice(objectEnd(text, start))}`;
  JSON.parse(updated);
  return updated;
}

const cell = text => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = value => `\`${cell(typeof value === 'string' ? value : JSON.stringify(value))}\``;
const typeNames = { string: 'string', integer: 'integer', number: 'number', boolean: 'boolean', object: 'object', array: 'list', null: 'null' };

function range(node, unit = '') {
  const low = node.minimum ?? (node.exclusiveMinimum !== undefined ? `more than ${node.exclusiveMinimum}` : undefined);
  if (low !== undefined && node.maximum !== undefined) return typeof low === 'number' ? `${low}–${node.maximum}${unit}` : `${low}, at most ${node.maximum}${unit}`;
  if (low !== undefined) return typeof low === 'number' ? `at least ${low}${unit}` : low;
  if (node.maximum !== undefined) return `at most ${node.maximum}${unit}`;
  return '';
}

function typeText(raw) {
  const node = resolved(raw);
  if (node.not !== undefined) return 'refused';
  if (node.anyOf) return node.anyOf.map(typeText).join(', or ');
  if (node.const !== undefined) return code(node.const);
  if (node.enum) return `one of ${node.enum.map(code).join(', ')}`;
  const types = Array.isArray(node.type) ? node.type : node.type ? [node.type] : [];
  const parts = types.map(type => {
    if (type === 'array') {
      const count = node.minItems !== undefined || node.maxItems !== undefined ? ` (${range({ minimum: node.minItems, maximum: node.maxItems }, ' entries')})` : '';
      return `list of ${node.items ? typeText(node.items) : 'values'}${count}`;
    }
    if (type === 'object' && plain(node.additionalProperties)) return `map of ${resolved(node.propertyNames ?? {}).title ?? 'name'} to ${typeText(node.additionalProperties)}`;
    if (type === 'integer' || type === 'number') { const limits = range(node); return limits ? `${typeNames[type]}, ${limits}` : typeNames[type]; }
    return typeNames[type];
  });
  return parts.join(' or ') || 'any';
}

function rows(node, path, out) {
  const flat = resolved(node);
  for (const branch of flat.anyOf ?? []) rows({ ...branch, description: undefined }, path, out);
  for (const [key, child] of Object.entries(flat.properties ?? {})) {
    const at = path ? `${path}.${key}` : key;
    const entry = resolved(child);
    if (!out.some(row => row.path === at)) out.push({ path: at, type: typeText(child), default: entry.default, description: `${entry.deprecated ? 'Deprecated. ' : ''}${entry.description ?? ''}` });
    rows(child, at, out);
  }
  const items = resolved(flat.items ?? {});
  if (flat.type === 'array' && items.properties) rows(items, `${path}[]`, out);
  if (plain(flat.additionalProperties)) {
    const value = resolved(flat.additionalProperties);
    if (value.properties) rows(value, `${path}.<${resolved(flat.propertyNames ?? {}).title ?? 'name'}>`, out);
  }
  return out;
}

function table(list) {
  return ['| Key | Type | Default | Meaning |', '| --- | --- | --- | --- |', ...list.map(row => `| ${code(row.path)} | ${cell(row.type)} | ${row.default === undefined ? '' : code(row.default)} | ${cell(row.description)} |`)].join('\n');
}

function reference() {
  const top = Object.entries(schema.properties).filter(([key]) => key !== '$schema');
  const scalar = top.filter(([, child]) => !resolved(child).properties && !(resolved(child).items && resolved(resolved(child).items).properties) && !resolved(child).anyOf);
  const blocks = top.filter(entry => !scalar.includes(entry));
  const lines = [
    '---',
    'type: reference',
    'audience: [operator, integrator, contributor, agent]',
    'owner: unfold',
    'generated_by: "npm run config:build"',
    '---',
    '',
    '# Configuration reference',
    '',
    '*Generated by [scripts/config-reference.mjs](../../scripts/config-reference.mjs) from [config.v1.schema.json](../contracts/config.v1.schema.json) and [config.v1.environment.json](../contracts/config.v1.environment.json). Do not edit by hand: change those two files and run `npm run config:build`. `npm run check` fails when this page, or the `config` part of the chart\'s [values.schema.json](../../ops/helm/unfold/values.schema.json), drifts from them.*',
    '',
    'Unfold reads a JSON configuration file named by `--config` or `UNFOLD_CONFIG`, and the environment variables below. At startup it checks the file against [config.v1.schema.json](../contracts/config.v1.schema.json) and refuses to start with one error that lists every problem with its JSON Pointer, for example:',
    '',
    '```text',
    'config/live.local.json: 2 problems:',
    '  /kubernetes/cpu: must match ^[0-9]+(\\.[0-9]+)?(m|[KMGT]i?)?$ (CPU limit of a workspace pod, such as 2.)',
    '  /auths: unknown key (did you mean auth?)',
    '```',
    '',
    'An unknown or misspelt key is an error, not ignored. After the schema, Unfold applies the rules that span several settings, such as live mode needing `ploeg` and `execution`, and stops at the first that fails. Add `"$schema": "' + schema.$id + '"` to a configuration file to have an editor check it while you type.',
    '',
    'A key ending in `Env` names an environment variable that holds a secret, so no secret sits in the file. Those variables are the deployment\'s choice and are not listed under [Environment variables](#environment-variables).',
    '',
    '## In the Helm chart',
    '',
    `The chart renders \`config:\` from its values into the file, and its [values.schema.json](../../ops/helm/unfold/values.schema.json) holds the same rules, so \`helm lint\` and \`helm template\` stop on a misspelt key. It writes ${Object.keys(chartOwned).map(key => code(key)).join(', ')} and ${Object.entries(chartOwnedNested).flatMap(([block, keys]) => Object.keys(keys).map(key => code(`${block}.${key}`))).join(', ')} itself and refuses them under \`config:\`. It also sets \`baseUrl\` when the chart value \`baseUrl\` is set, and \`delivery\` and \`decider\` from their own chart values when those are enabled.`,
    '',
    '## Environment variables',
    '',
    '| Name | Type | Default | Overrides | Meaning |',
    '| --- | --- | --- | --- | --- |',
    ...environment.variables.map(variable => `| ${code(variable.name)} | ${cell(variable.type)} | ${variable.default === undefined ? '' : code(variable.default)} | ${variable.overrides ? code(variable.overrides) : ''} | ${cell(variable.description)} |`),
    '',
    `${environment.workspaceVariables.description} They are ${environment.workspaceVariables.names.map(name => code(name)).join(', ')}.`,
    '',
    '## Configuration file',
    '',
    `${schema.description.split('. ')[0]}. Keys are written as dotted paths: \`[]\` is any entry of a list and \`<name>\` any key of a map.`,
    '',
    '### Top-level settings',
    '',
    table(scalar.map(([key, child]) => { const entry = resolved(child); return { path: key, type: typeText(child), default: entry.default, description: `${entry.deprecated ? 'Deprecated. ' : ''}${entry.description ?? ''}` }; })),
  ];
  for (const [key, child] of blocks) {
    const entry = resolved(child);
    lines.push('', `### ${key}`, '', `${entry.deprecated ? 'Deprecated. ' : ''}${entry.description ?? ''}${entry.default !== undefined ? ` Default: ${code(entry.default)}.` : ''}`, '', table(rows(child, key, [])));
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outputs = [[referencePath, reference()], [chartSchemaPath, chartSchemaText()]];
  const drifted = outputs.filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text).map(([path]) => path.slice(root.length));
  if (check) {
    if (drifted.length) {
      process.stderr.write(`${drifted.join(', ')} drifted from docs/contracts/config.v1.schema.json and config.v1.environment.json; run npm run config:build\n`);
      process.exitCode = 1;
    }
  } else for (const [path, text] of outputs) writeFileSync(path, text);
}
